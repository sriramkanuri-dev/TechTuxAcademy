const dictionaries = { en, te } as const;

interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: (key: DictionaryKey) => string;
  pick: (english: string, telugu?: string | null) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    return localStorage.getItem('tta-language') === 'te' ? 'te' : 'en';
  });

  useEffect(() => {
    localStorage.setItem('tta-language', language);
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (next: Language) => setLanguageState(next);
  const toggleLanguage = () => setLanguageState((current) => (current === 'en' ? 'te' : 'en'));
  const t = (key: DictionaryKey) => dictionaries[language][key] ?? en[key];
  const pick = (english: string, telugu?: string | null) =>
    language === 'te' && telugu ? telugu : english;

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t, pick }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
